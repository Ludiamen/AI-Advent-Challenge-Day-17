# --- отчёт ------------------------------------------------------------------------

def отчёт_в_markdown(итоги: list[Итог], модель: str, секунд: float) -> str:
    всего = sum(len(и.сошлось) for и in итоги)
    сошлось = sum(1 for и in итоги for _, ок in и.сошлось if ок)
    строки = [
        "# Результат консольной проверки Дня 17",
        "",
        f"Прогон: `python check_cli.py`, модель для живых вызовов **{модель or 'по роли'}**, "
        f"память в `{ПАМЯТЬ_ОТН}/`.",
        f"Дата: {time.strftime('%Y-%m-%d %H:%M')}. Заняло {секунд / 60:.1f} мин.",
        "",
        f"**Ожиданий проверено: {всего}, сошлось: {сошлось}, "
        f"расхождений: {всего - сошлось}.**",
        "",
        "Каждая строка — отдельный процесс. Проверяются три пласта: свой инструмент",
        "MCP этого дня (сервер вокруг API трекера, вызов вручную и моделью, заявка",
        "на изменение), подключение MCP из Дня 16 и наследство Дней 11–15 — чтобы",
        "видеть, что не сломалось.",
        "",
        "## Сводка",
        "",
        "| шаг | проверка | команда | итог | секунд |",
        "|---|---|---|---|---|",
    ]
    for и in итоги:
        ключи = (и.команда.replace(f"--память-в {ПАМЯТЬ_ОТН} ", "")
                 .replace(f"--модель {модель} ", "").strip())
        строки.append(f"| {и.шаг.номер} | {и.шаг.название} | `{ключи}` | "
                      f"{'ок' if и.удача else '**расхождение**'} | {и.секунд:.1f} |")
    строки += ["", "## Подробности", ""]
    for и in итоги:
        строки.append(f"### {и.шаг.номер}. {и.шаг.название}")
        строки.append("")
        строки.append(f"```\n$ python {и.команда}\n```")
        if и.шаг.фон:
            строки.append("")
            строки.append(f"Во время шага работал сервер: `python {' '.join(и.шаг.фон[1:])}`")
        строки.append("")
        for описание, ок in и.сошлось:
            строки.append(f"- {'✓' if ок else '✗'} {описание}")
        строки.append("")
        кусок = "\n".join(и.вывод.strip().splitlines()[:40])
        if кусок:
            # Четыре кавычки: в выводе бывают тройные, и они рвали бы разметку.
            строки += ["<details><summary>вывод</summary>", "", "````", кусок, "````", "",
                       "</details>", ""]
    строки += [
        "## Что это доказывает",
        "",
        "| Пункт задания дня 17 | Шаги прогона |",
        "|---|---|",
        "| свой MCP-сервер вокруг API | 1.1, 1.3, 2.1, 2.2 (сервер поверх HTTP-API трекера) |",
        "| регистрация инструмента | 1.1 (пять инструментов, пометки), 2.1 (сверка со списком в коде) |",
        "| описание входных параметров | 1.2 (JSON-схема, required, границы), 2.1 (у каждого параметра описание) |",
        "| возврат результата | 1.5, 6.5, 2.1 (сверка с прямым запросом к API) |",
        "| инструмент подключён к агенту | 1.4 (что досталось модели и почём) |",
        "| вызов из приложения | 1.5 (руками), 6.1 (по решению модели), 6.4 (по подтверждённой заявке) |",
        "| результат получен и использован | 6.1 (ключи задач из трекера в ответе), 6.5 |",
        "| изменение — только с подтверждения | 6.2, 6.3, 6.4, 6.6 |",
        "| сбои понятны и не вешают | 1.6, 1.7, 2.2, 4.1–4.3 |",
        "",
        "| Наследство прошлых дней — не сломалось | Шаги |",
        "|---|---|",
        "| подключение MCP, список инструментов, фильтр (День 16) | 3.1–3.9 |",
        "| слои памяти и разбор промпта (День 11) | 5.1, 7.2 |",
        "| заготовки и профиль (День 12) | 5.2, 5.3 |",
        "| пауза поверх этапа, продолжение в другом процессе (День 13) | 5.8, 5.9 |",
        "| инварианты и отказ за ноль токенов (День 14) | 5.4, 7.1 |",
        "| ворота переходов (День 15) | 5.5, 5.7 |",
        "| диалоговый режим | 5.10 |",
        "",
    ]
    return "\n".join(строки)


def main() -> int:
    разбор = argparse.ArgumentParser(
        description="Прогон консольного чек-листа Дня 17 с отчётом в markdown.")
    разбор.add_argument("--модель", dest="model", default="ds-flash",
                        help="модель для живых вызовов (по умолчанию ds-flash)")
    разбор.add_argument("--в", dest="report", default="CLI-CHECK-RESULTS.md",
                        help="файл отчёта (по умолчанию CLI-CHECK-RESULTS.md)")
    разбор.add_argument("--без-модели", dest="no_model", action="store_true",
                        help="пропустить шаги с живым вызовом модели")
    аргументы = разбор.parse_args()

    shutil.rmtree(ПАМЯТЬ, ignore_errors=True)
    начало = time.time()
    итоги: list[Итог] = []

    трекер = МокТрекера()
    трекер.запустить()
    print(f"{LINE}\nКОНСОЛЬНАЯ ПРОВЕРКА ДНЯ 17, модель {аргументы.model}")
    print(f"Мок-трекер: {трекер.адрес}, данные в {os.path.relpath(трекер.данные, КОРЕНЬ)}\n{LINE}")
    try:
        for шаг in шаги(not аргументы.no_model, трекер):
            итог = запустить(шаг, аргументы.model)
            итоги.append(итог)
            print(f"  {шаг.номер} {шаг.название}: {'ок' if итог.удача else 'РАСХОЖДЕНИЕ'} "
                  f"({итог.секунд:.1f} с)")
            for описание, ок in итог.сошлось:
                if not ок:
                    print(f"      ✗ {описание}")
    finally:
        трекер.остановить()

    текст = отчёт_в_markdown(итоги, аргументы.model, time.time() - начало)
    with open(os.path.join(КОРЕНЬ, аргументы.report), "w", encoding="utf-8") as файл:
        файл.write(текст)

    расхождений = sum(1 for и in итоги for _, ок in и.сошлось if not ок)
    print(LINE)
    print(f"Отчёт записан в {аргументы.report}. Расхождений: {расхождений}.")
    print(f"Память прогона осталась в «{ПАМЯТЬ_ОТН}» — её можно посмотреть глазами.")
    return 1 if расхождений else 0


if __name__ == "__main__":
    sys.exit(main())
